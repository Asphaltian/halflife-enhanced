	public float GetSkillCvar( string name )
	{
		var cvar = $"{name}{SkillLevel}";
		var value = Cvar.GetFloat( cvar );

		if ( value <= 0f )
			Log.Info( $"\n\n** GetSkillCVar Got a zero for {cvar} **\n\n" );

		return value;
	}

